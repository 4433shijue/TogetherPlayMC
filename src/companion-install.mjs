import fs from 'node:fs/promises';
import path from 'node:path';
import {randomBytes,createHash} from 'node:crypto';
import {root,runtime} from './paths.mjs';
import {assertGamesClosed} from './game-profiles.mjs';

export async function configuredProfiles(store){
  const saved=store?.get('gameProfiles');if(saved)return saved;
  let config;try{config=JSON.parse(await fs.readFile(path.join(root,'config/experiment.json'),'utf8'));}catch{return [];}
  return [{id:'vanilla1201',name:'原版 1.20.1',loader:'fabric',gameDir:path.join(runtime,'companion-player')},{id:'elements146',name:'元素觉醒 1.4.6',loader:'forge',gameDir:path.dirname(config.sourceClientJar)}];
}
export function pairProfile(store,profile){
  const key=`companion-profile:${profile.id}`,existing=store.get(key);
  if(existing){const updated={...existing,...profile};store.set(key,updated);return updated;}
  const paired={...profile,token:randomBytes(32).toString('hex'),paired:new Date().toISOString()};store.set(key,paired);return paired;
}
export function publicProfile(profile){const {token,...safe}=profile;return safe;}

export async function installProfile(profile,{endpoint,directory,dist=path.join(root,'artifacts/mods')}={}) {
  await assertGamesClosed();
  if(!['forge','fabric'].includes(profile.loader))throw new Error('不支持此加载器。');
  const game=path.resolve(profile.gameDir),mods=path.join(game,'mods'),cfg=path.join(game,'config');
  await fs.access(game);await fs.mkdir(mods,{recursive:true});await fs.mkdir(cfg,{recursive:true});
  const name=`together-companion-${profile.loader}-1.20.1-0.6.0.jar`,jar=await fs.readFile(path.join(dist,name));
  let apiArtifact=null;
  if(profile.loader==='fabric'&&!(await fs.readdir(mods)).some(f=>/^fabric-api-.*\.jar$/.test(f))){
    const apiName='fabric-api-0.92.2+1.20.1.jar',cache=path.join(runtime,'cache',apiName),url='https://maven.fabricmc.net/net/fabricmc/fabric-api/fabric-api/0.92.2+1.20.1/'+apiName;
    // Pinned artifact verified against the publisher's Maven SHA-1; cache installation works offline.
    const sha='625ee015ee426d9b677382a7bb661383d89c0807';
    await fs.mkdir(path.dirname(cache),{recursive:true});
    let data;try{data=await fs.readFile(cache);}catch{}
    if(!data||createHash('sha1').update(data).digest('hex')!==sha.trim()){
      const response=await fetch(url,{signal:AbortSignal.timeout(60000)});if(!response.ok)throw new Error('Fabric API 下载失败。');data=Buffer.from(await response.arrayBuffer());
      if(createHash('sha1').update(data).digest('hex')!==sha.trim())throw new Error('Fabric API 校验失败。');await fs.writeFile(cache,data);
    }
    apiArtifact={name:apiName,data};
  }
  const backup=path.join(root,'work','v06-install-backups',profile.id,new Date().toISOString().replaceAll(':','-'));
  await fs.mkdir(backup,{recursive:true});const changes=[];
  const preserve=async file=>{try{await fs.copyFile(file,path.join(backup,path.basename(file)));return true;}catch(e){if(e.code==='ENOENT')return false;throw e;}};
  // Only this project's previous artifacts are retired. Other mods and saves are untouched.
  for(const old of await fs.readdir(mods))if(/^together-companion-(?:fabric|forge)-1\.20\.1-[\d.]+\.jar$/.test(old)||old==='togetherplay-bridge.jar'){
    await preserve(path.join(mods,old));changes.push(old);
  }
  const configFile=path.join(cfg,'together-companion.json');await preserve(configFile);
  // Fixed local launcher generated by the installer; neither model output nor mod metadata supplies commands.
  const launcher=path.join(cfg,'together-companion-start.vbs');await preserve(launcher);
  const quote=value=>'"'+String(value).replaceAll('"','""')+'"';
  const command=`"${path.join(runtime,'node/node.exe')}" "${path.join(root,'src/server.mjs')}"`;
  const parsed=new URL(endpoint);
  const script=`Set shell = CreateObject("WScript.Shell")\r\nshell.CurrentDirectory = ${quote(root)}\r\nshell.Environment("PROCESS")("TOGETHER_DATA") = ${quote(path.resolve(directory))}\r\nshell.Environment("PROCESS")("TOGETHER_PORT") = ${quote(parsed.port)}\r\nshell.Run ${quote(command)}, 0, False\r\n`;
  const manifest={profile:publicProfile(profile),installed:name,sha256:createHash('sha256').update(jar).digest('hex'),backup,replaced:changes,at:new Date().toISOString()};
  // All backups finish before the first managed file is replaced.
  try{
    for(const old of changes)await fs.unlink(path.join(mods,old));
    await fs.writeFile(path.join(mods,name),jar);
    if(apiArtifact)await fs.writeFile(path.join(mods,apiArtifact.name),apiArtifact.data);
    await fs.writeFile(launcher,Buffer.concat([Buffer.from([255,254]),Buffer.from(script,'utf16le')]));
    await fs.writeFile(configFile,JSON.stringify({protocol:1,profileId:profile.id,endpoint,token:profile.token,launcher,mode:'companion'},null,2));
    await fs.writeFile(path.join(backup,'installation.json'),JSON.stringify(manifest,null,2));return manifest;
  }catch(error){
    await restoreProfile(manifest);
    if(apiArtifact)await fs.unlink(path.join(mods,apiArtifact.name)).catch(()=>{});
    throw Error('安装未完成，已恢复原伙伴文件：'+error.message);
  }
}
export async function restoreProfile(manifest){
 await assertGamesClosed();const base=path.resolve(root,'work/v06-install-backups'),backup=path.resolve(manifest.backup);
 if(!backup.startsWith(base+path.sep))throw Error('备份路径无效。');
 const game=manifest.profile.gameDir,jar=path.join(game,'mods',manifest.installed);
 if(!/^together-companion-.*\.jar$/.test(manifest.installed))throw Error('备份记录无效。');
 // Read every backup before changing the installed files; incomplete backups cannot erase a working mod.
 const names=(await fs.readdir(backup)).filter(name=>/^together-companion-(?:fabric|forge)-.*\.jar$/.test(name)||name==='togetherplay-bridge.jar');
 const jars=await Promise.all(names.map(async name=>({name,bytes:await fs.readFile(path.join(backup,name))})));
 for(const name of manifest.replaced??[])if(!names.includes(name))throw Error('安装备份不完整，已保留当前伙伴。');
 await fs.unlink(jar).catch(e=>{if(e.code!=='ENOENT')throw e;});
 for(const entry of jars)await fs.writeFile(path.join(game,'mods',entry.name),entry.bytes);
 for(const name of ['together-companion.json','together-companion-start.vbs']){const source=path.join(backup,name),target=path.join(game,'config',name);try{await fs.copyFile(source,target);}catch(e){if(e.code==='ENOENT')await fs.unlink(target).catch(()=>{});else throw e;}}
 return {ok:true,message:'已恢复更新前的伙伴文件，存档和其他模组保留。'};
}
